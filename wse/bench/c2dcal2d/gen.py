#!/usr/bin/env python3
"""layout.csl for Addendum G: PE (x, y) runs x-configuration configs()[y] and y-configuration configs()[x]."""
from cases import configs, P
C = configs(); assert len(C) == P
L = ["// generated by wse/bench/c2dcal2d/gen.py (Stage 1 Addendum G calibration set)", "param Pw: u16;", "param Ph: u16;",
     'const memcpy = @import_module("<memcpy/get_params>", .{ .width = Pw, .height = Ph });',
     'const c2d = @import_module("<collectives_2d/params>");', "layout {", "  @set_rectangle(Pw, Ph);"]
for x in range(P):
    L.append(f"  {{ const mp = memcpy.get_params({x});")
    for y in range(P):
        cx, cy = C[y], C[x]
        L.append(f"    {{ const cp = c2d.get_params({x}, {y}, .{{ .x_colors = .{{ @get_color(0), @get_color(1) }}, "
                 f".x_entrypoints = .{{ @get_local_task_id(14), @get_local_task_id(15) }}, "
                 f".y_colors = .{{ @get_color(4), @get_color(5) }}, .y_entrypoints = .{{ @get_local_task_id(16), @get_local_task_id(17) }} }});")
        L.append(f'      @set_tile_code({x}, {y}, "pe2d.csl", .{{ .memcpy_params = mp, .c2d_params = cp, '
                 f'.XOP = {cx["op"]}, .XROOT = {cx["root"]}, .XCOUNT = {cx["count"]}, '
                 f'.YOP = {cy["op"]}, .YROOT = {cy["root"]}, .YCOUNT = {cy["count"]}, .PXN = {P}, .PYN = {P} }}); }}')
    L.append("  }")
L += ['  @export_name("time_buf_u16", [*]u16, true);', '  @export_name("main", fn()void);',
      '  @export_name("f_enable_timer", fn()void);', '  @export_name("f_memcpy_timestamps", fn()void);', "}"]
open("layout.csl", "w").write("\n".join(L) + "\n")
print(f"P={P} configs={len(C)}")
