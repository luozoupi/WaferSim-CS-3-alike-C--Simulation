#!/usr/bin/env python3
"""Stage 1 / M1: build layout.csl for a fabric case (routes + per-PE roles).  Kernel rectangle W x H; tile (x, y)."""
import json, sys
from cases import tag
OPP = {"E": "W", "W": "E", "N": "S", "S": "N"}
CSL = {"E": "EAST", "W": "WEST", "N": "NORTH", "S": "SOUTH", "R": "RAMP"}
STEP = {"E": (1, 0), "W": (-1, 0), "N": (0, -1), "S": (0, 1)}


class Spec:
    def __init__(self, W, H):
        self.W, self.H = W, H
        self.routes = {}          # (x, y) -> {colour: (rx, [tx...])}
        self.roles = {}           # (x, y) -> dict(send_c, send_n, recv=[(c, n)], relay, rdelay)

    def route(self, x, y, c, rx, tx):
        r = self.routes.setdefault((x, y), {})
        if c in r:                # multicast tap: extend the tx set
            assert r[c][0] == rx, (x, y, c, r[c], rx)
            r[c] = (rx, sorted(set(r[c][1]) | set(tx)))
        else:
            r[c] = (rx, list(tx))

    def role(self, x, y):
        return self.roles.setdefault((x, y), dict(send_c=0, send_n=0, recv=[], relay=0, rdelay=0))

    def path(self, x, y, dirs, c):
        """route colour c from (x, y) along the direction list; returns the destination tile"""
        rx = "R"
        for i, d in enumerate(dirs):
            self.route(x, y, c, rx, [d]); rx = OPP[d]
            x, y = x + STEP[d][0], y + STEP[d][1]
        self.route(x, y, c, rx, ["R"])
        return x, y


def build(c):
    f = c["family"]
    if f == "straight" or f == "backpressure":
        d = c.get("dir", "E"); h = c["hops"]; B = c["B"]
        W, H = (h + 1, 1) if d in "EW" else (1, h + 1)
        s = Spec(W, H)
        x0 = {"E": 0, "W": h}.get(d, 0); y0 = {"S": 0, "N": h}.get(d, 0)
        dx, dy = s.path(x0, y0, [d] * h, 1)
        s.role(x0, y0).update(send_c=1, send_n=B)
        s.role(dx, dy).update(recv=[(1, B)], rdelay=c.get("delay", 0))
        return s
    if f == "turn":
        a, b, B = c["a"], c["b"], c["B"]; d1, d2 = c["d1"], c["d2"]
        horiz1 = d1 in "EW"
        W, H = (a + 1, b + 1) if horiz1 else (b + 1, a + 1)
        s = Spec(W, H)
        x0 = 0 if (d1 == "E" or d2 == "E") else W - 1
        y0 = 0 if (d1 == "S" or d2 == "S") else H - 1
        dx, dy = s.path(x0, y0, [d1] * a + [d2] * b, 1)
        s.role(x0, y0).update(send_c=1, send_n=B)
        s.role(dx, dy).update(recv=[(1, B)])
        return s
    if f == "multicast":
        L, fo, B = c["L"], c["fanout"], c["B"]
        s = Spec(L + 1, 1)
        s.path(0, 0, ["E"] * L, 1)
        s.role(0, 0).update(send_c=1, send_n=B)
        for k in range(1, fo + 1):
            x = k * L // fo
            if x < L:
                s.route(x, 0, 1, "W", ["R"])
            s.role(x, 0).update(recv=[(1, B)])
        return s
    if f == "contention":
        k, gap, tail, B = c["k"], c["gap"], c["tail"], c["B"]
        xd = (k - 1) * gap + tail
        s = Spec(xd + 1, 1)
        for i in range(k):
            xs = i * gap; col = 1 + i
            s.path(xs, 0, ["E"] * (xd - xs), col)
            s.role(xs, 0).update(send_c=col, send_n=B)
        s.role(xd, 0).update(recv=[(1 + i, B) for i in range(k)])
        return s
    if f == "relay":
        N, B = c["N"], c["B"]
        s = Spec(N + 1, 1)
        for i in range(N):
            col = 6 + (i % 2)
            s.route(i, 0, col, "R", ["E"]); s.route(i + 1, 0, col, "W", ["R"])
        s.role(0, 0).update(send_c=6, send_n=B)
        for i in range(1, N + 1):
            r = s.role(i, 0); r["recv"] = [(6 + ((i - 1) % 2), B)]
            if i < N:
                r.update(send_c=6 + (i % 2), send_n=B, relay=1)
        return s
    raise ValueError(f)


def layout(s):
    lines = ["// generated by wse/bench/fabric/gen.py", "param W: u16;", "param H: u16;",
             'const memcpy = @import_module("<memcpy/get_params>", .{ .width = W, .height = H });', "layout {",
             "  @set_rectangle(W, H);"]
    for x in range(s.W):
        lines.append(f"  {{ const mp = memcpy.get_params({x});")
        for y in range(s.H):
            r = s.role(x, y); rc = [cc for cc, n in r["recv"]] + [0] * (4 - len(r["recv"]))
            rn = [n for cc, n in r["recv"]] + [1] * (4 - len(r["recv"]))
            lines.append(f'    @set_tile_code({x}, {y}, "pe.csl", .{{ .memcpy_params = mp, .SEND_C = {r["send_c"]}, .SEND_N = {r["send_n"]}, '
                         f'.NRECV = {len(r["recv"])}, .RC0 = {rc[0]}, .RC1 = {rc[1]}, .RC2 = {rc[2]}, .RC3 = {rc[3]}, '
                         f'.RN0 = {rn[0]}, .RN1 = {rn[1]}, .RN2 = {rn[2]}, .RN3 = {rn[3]}, .RELAY = {r["relay"]}, .RDELAY = {r["rdelay"]} }});')
            for col, (rx, tx) in sorted(s.routes.get((x, y), {}).items()):
                txs = ", ".join(CSL[t] for t in tx)
                lines.append(f"    @set_color_config({x}, {y}, @get_color({col}), .{{ .routes = .{{ .rx = .{{ {CSL[rx]} }}, .tx = .{{ {txs} }} }} }});")
        lines.append("  }")
    lines += ['  @export_name("time_buf_u16", [*]u16, true);', '  @export_name("main", fn()void);',
              '  @export_name("f_enable_timer", fn()void);', '  @export_name("f_memcpy_timestamps", fn()void);', "}"]
    return "\n".join(lines) + "\n"


DMASK = {"R": 1, "N": 2, "S": 4, "E": 8, "W": 16}
DIDX = {"R": 0, "N": 1, "S": 2, "E": 3, "W": 4}


def spec_text(s):
    """plain-text spec for the C++ fabric harness"""
    out = [f"GRID {s.W} {s.H}"]
    for (x, y), cols in sorted(s.routes.items()):
        for col, (rx, tx) in sorted(cols.items()):
            out.append(f"ROUTE {x} {y} {col} {DIDX[rx]} {sum(DMASK[t] for t in tx)}")
    for (x, y), r in sorted(s.roles.items()):
        if r["send_n"]:
            out.append(f"SEND {x} {y} {r['send_c']} {r['send_n']} {r['relay']}")
        for col, n in r["recv"]:
            out.append(f"RECV {x} {y} {col} {n} {r['rdelay']}")
    return "\n".join(out) + "\n"


# ---- Addendum A: switch-advance / teardown families on pe_ctl.csl ----
KIND = {"data": 1, "adv": 2, "ctl_adv": 3, "ctl_td": 4, "ctl_td_rst": 5, "ctl_td_td": 6}
CTL_FAMILIES = ("sa_tx", "sa_rx", "sa_chain", "sa_ring", "td_line")
MARK = 9                          # marker colour (R -> R) for teardown-handler timing


class CtlSpec(Spec):
    def __init__(self, W, H):
        super().__init__(W, H)
        self.sw = {}              # (x, y, c) -> dict(pos={1: dict(rx=, tx=[...])}, cur=0, ring=False, pop=None)

    def role(self, x, y):
        return self.roles.setdefault((x, y), dict(send_c=0, segs=[], recv=[], tdc=0, mkc=0, tdx=0, p2s=0, p2r=0))

    def switch(self, x, y, c, pos, rx=None, tx=None):
        d = self.sw.setdefault((x, y, c), dict(pos={}, cur=0, ring=False, pop=None))
        e = d["pos"].setdefault(pos, {})
        if rx is not None:
            e["rx"] = rx
        if tx is not None:
            e["tx"] = list(tx)
        return d


def build_ctl(c):
    f = c["family"]
    if f == "sa_tx":
        m, B1, B2 = c["m"], c["B1"], c["B2"]; L = 2 * m
        s = CtlSpec(L + 1, 1)
        s.route(0, 0, 1, "R", ["E"])
        for x in range(1, L):
            s.route(x, 0, 1, "W", ["R"] if x == m else ["E"])
        s.route(L, 0, 1, "W", ["R"])
        s.switch(m, 0, 1, 1, tx=["E"])
        s.role(0, 0).update(send_c=1, segs=[("data", B1), ("ctl_adv", 1), ("data", B2)])
        s.role(m, 0)["recv"] = [(1, B1)]
        s.role(L, 0)["recv"] = [(1, B2)]
        return s
    if f == "sa_rx":
        m, B = c["m"], c["B"]; L = 2 * m
        s = CtlSpec(L + 1, 1)
        s.route(0, 0, 1, "R", ["E"])
        for x in range(1, m):
            s.route(x, 0, 1, "W", ["E"])
        s.route(m, 0, 1, "W", ["R"]); s.switch(m, 0, 1, 1, rx="E")
        for x in range(m + 1, L):
            s.route(x, 0, 1, "E", ["W"])
        s.route(L, 0, 1, "R", ["W"])
        s.role(0, 0).update(send_c=1, segs=[("data", B), ("ctl_adv", 1)])
        s.role(L, 0).update(send_c=1, segs=[("data", B)])
        s.role(m, 0)["recv"] = [(1, 2 * B)]
        return s
    if f == "sa_chain":
        N, B = c["N"], c["B"]
        s = CtlSpec(N + 1, 1)
        s.route(0, 0, 1, "R", ["E"])
        for x in range(1, N):
            s.route(x, 0, 1, "R", ["E"]); s.switch(x, 0, 1, 1, rx="W")
        s.route(N, 0, 1, "W", ["R"])
        for x in range(N):
            s.role(x, 0).update(send_c=1, segs=[("adv", B)])
        s.role(N, 0)["recv"] = [(1, N * B)]
        return s
    if f == "sa_ring":
        B = c["B"]
        s = CtlSpec(3, 3)
        s.route(1, 1, 1, "R", ["N"])
        for pos, d in ((1, "W"), (2, "E"), (3, "S")):
            s.switch(1, 1, 1, pos, tx=[d])
        sw = s.sw[(1, 1, 1)]; sw["cur"] = 1; sw["ring"] = True
        for (x, y, rx) in ((1, 0, "S"), (0, 1, "E"), (2, 1, "W"), (1, 2, "N")):
            s.route(x, y, 1, rx, ["R"]); s.role(x, y)["recv"] = [(1, B)]
        s.role(1, 1).update(send_c=1, segs=[("ctl_adv", 1), ("data", B)] * 4)
        return s
    if f == "td_line":
        L, B, P2 = c["L"], c["B"], c["P2"]
        s = CtlSpec(L + 1, 1)
        s.route(0, 0, 1, "R", ["E"])
        for x in range(1, L):
            s.route(x, 0, 1, "W", ["R", "E"])
        s.route(L, 0, 1, "W", ["R"])
        for x in range(L + 1):
            s.route(x, 0, MARK, "R", ["R"])
        s.role(0, 0).update(send_c=1, segs=[("data", B), ("ctl_td", 1)], tdc=1, mkc=MARK, tdx=1, p2s=P2)
        for x in range(1, L + 1):
            s.role(x, 0).update(recv=[(1, B)], tdc=1, mkc=MARK, tdx=1, p2r=P2)
        return s
    raise ValueError(f)


def layout_ctl(s):
    lines = ["// generated by wse/bench/fabric/gen.py (Addendum A, pe_ctl.csl)", "param W: u16;", "param H: u16;",
             'const memcpy = @import_module("<memcpy/get_params>", .{ .width = W, .height = H });', "layout {",
             "  @set_rectangle(W, H);"]
    for x in range(s.W):
        lines.append(f"  {{ const mp = memcpy.get_params({x});")
        for y in range(s.H):
            r = s.role(x, y)
            segs = [(KIND[k] << 12) | n for k, n in r["segs"]] + [0] * (8 - len(r["segs"]))
            rc = [cc for cc, n in r["recv"]] + [0] * (2 - len(r["recv"]))
            rn = [n for cc, n in r["recv"]] + [1] * (2 - len(r["recv"]))
            sbn = max([n for k, n in r["segs"] if k in ("data", "adv")] + [r["p2s"], 1])
            rbn0 = max(rn[0], r["p2r"], 1)
            segp = ", ".join(f".SEG{i} = {v}" for i, v in enumerate(segs))
            lines.append(f'    @set_tile_code({x}, {y}, "pe_ctl.csl", .{{ .memcpy_params = mp, .SEND_C = {r["send_c"]}, {segp}, '
                         f'.NRECV = {len(r["recv"])}, .RC0 = {rc[0]}, .RN0 = {rn[0]}, .RC1 = {rc[1]}, .RN1 = {rn[1]}, '
                         f'.TDC = {r["tdc"]}, .MKC = {r["mkc"]}, .TDX = {r["tdx"]}, .P2S = {r["p2s"]}, .P2R = {r["p2r"]}, '
                         f'.SBN = {sbn}, .RBN0 = {rbn0}, .RBN1 = {rn[1]} }});')
            for col, (rx, tx) in sorted(s.routes.get((x, y), {}).items()):
                txs = ", ".join(CSL[t] for t in tx)
                cfg = f".routes = .{{ .rx = .{{ {CSL[rx]} }}, .tx = .{{ {txs} }} }}"
                sw = s.sw.get((x, y, col))
                if sw:
                    parts = []
                    for pos, e in sorted(sw["pos"].items()):
                        pe = []
                        if "rx" in e:
                            pe.append(f".rx = {CSL[e['rx']]}")
                        if "tx" in e:
                            pe.append(f".tx = {CSL[e['tx'][0]]}" if len(e["tx"]) == 1 else ".tx = .{ " + ", ".join(CSL[t] for t in e["tx"]) + " }")
                        parts.append(f".pos{pos} = .{{ {', '.join(pe)} }}")
                    if sw["cur"]:
                        parts.append(f".current_switch_pos = {sw['cur']}")
                    if sw["ring"]:
                        parts.append(".ring_mode = true")
                    if sw["pop"]:
                        parts.append(f".pop_mode = .{{ .{sw['pop']} = true }}")
                    cfg += ", .switches = .{ " + ", ".join(parts) + " }"
                lines.append(f"    @set_color_config({x}, {y}, @get_color({col}), .{{ {cfg} }});")
        lines.append("  }")
    lines += ['  @export_name("time_buf_u16", [*]u16, true);', '  @export_name("main", fn()void);',
              '  @export_name("f_enable_timer", fn()void);', '  @export_name("f_memcpy_timestamps", fn()void);', "}"]
    return "\n".join(lines) + "\n"


POPI = {None: 0, "always_pop": 1, "pop_on_advance": 2, "pop_on_advance_or_nop": 3}


def spec_text_ctl(s):
    """plain-text spec for the C++ harness (wse/stage1/fabsim2.cpp)"""
    out = [f"GRID {s.W} {s.H}"]
    for (x, y), cols in sorted(s.routes.items()):
        for col, (rx, tx) in sorted(cols.items()):
            out.append(f"ROUTE {x} {y} {col} {DIDX[rx]} {sum(DMASK[t] for t in tx)}")
    for (x, y, col), sw in sorted(s.sw.items()):
        for pos, e in sorted(sw["pos"].items()):
            out.append(f"SW {x} {y} {col} {pos} {DIDX[e['rx']] if 'rx' in e else -1} {sum(DMASK[t] for t in e['tx']) if 'tx' in e else 0}")
        out.append(f"SWC {x} {y} {col} {sw['cur']} {int(sw['ring'])} {POPI[sw['pop']]}")
    for (x, y), r in sorted(s.roles.items()):
        out.append(f"PE {x} {y} {r['send_c']} {r['tdc']} {r['mkc']} {r['tdx']} {r['p2s']} {r['p2r']}")
        for k, n in r["segs"]:
            out.append(f"SEG {x} {y} {KIND[k]} {n}")
        for col, n in r["recv"]:
            out.append(f"RECV {x} {y} {col} {n} 0")
    return "\n".join(out) + "\n"


def build_any(c):
    return build_ctl(c) if c["family"] in CTL_FAMILIES else build(c)


if __name__ == "__main__":
    from cases import all_cases
